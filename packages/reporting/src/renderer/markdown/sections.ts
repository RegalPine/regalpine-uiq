// ─── §30-31 Conformance ────────────────────────────────────────────

export function renderConformance(report: UIQualityReport): string {
  const lines: string[] = [];
  lines.push('## 8. Conformance');
  lines.push('');
  if (!report.conformance) {
    lines.push('Conformance evaluation was not performed for the selected scope.');
    lines.push('');
    return lines.join('\n');
  }
  const c = report.conformance;
  lines.push(`**Level:** ${escapeMarkdown(c.level)}`);
  lines.push('');
  lines.push(`**Status:** ${c.failed === 0 && c.errors === 0 ? 'PASS' : 'FAIL'}`);
  lines.push('');
  lines.push('| Category | Passed | Failed |');
  lines.push('|---|---:|---:|');
  lines.push(`| Total | ${c.passed} | ${c.failed} |`);
  lines.push(`| Unknown | ${c.unknown} | — |`);
  lines.push(`| Errors | ${c.errors} | — |`);
  lines.push('');
  return lines.join('\n');
}

// ─── §28-29 Regression ─────────────────────────────────────────────

export function renderRegression(report: UIQualityReport): string {
  const lines: string[] = [];
  lines.push('## 9. Regression Analysis');
  lines.push('');
  if (!report.regression) {
    lines.push('Regression analysis was not performed for the selected scope.');
    lines.push('');
    return lines.join('\n');
  }
  const r = report.regression.summary;
  lines.push('| Category | Count |');
  lines.push('|---|---:|');
  lines.push(`| NEW_FAILURE | ${r.newFailures} |`);
  lines.push(`| FIXED_FAILURE | ${r.fixedFailures} |`);
  lines.push(`| PERSISTING_FAILURE | ${r.persistingFailures} |`);
  lines.push(`| CHANGED_RESULT | ${r.changedResults} |`);
  lines.push(`| NEW_UNKNOWN | ${r.newUnknowns} |`);
  lines.push(`| RESOLVED_UNKNOWN | ${r.resolvedUnknowns} |`);
  lines.push('');
  // Regression detail: new failures (ADDED = new in current)
  const newFailures = report.regression.findingChanges.filter((fc) => fc.status === 'ADDED');
  if (newFailures.length > 0) {
    lines.push('### New Failures');
    lines.push('');
    for (const fc of newFailures) {
      const subject = fc.after?.subjectId ?? fc.logicKey;
      lines.push(`- ${escapeMarkdown(subject)}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

// ─── §25-26 Recommendations ────────────────────────────────────────

export function renderRecommendations(report: UIQualityReport): string {
  const lines: string[] = [];
  lines.push('## 10. Improvement Recommendations');
  lines.push('');
  if (report.recommendations.length === 0) {
    lines.push('No improvement recommendations were generated for the selected scope.');
    lines.push('');
    return lines.join('\n');
  }
  for (const r of report.recommendations) {
    lines.push(`### ${escapeMarkdown(r.id)} — ${escapeMarkdown(r.title)}`);
    lines.push('');
    lines.push(`**Dimension:** ${escapeMarkdown(r.dimension)}`);
    lines.push('');
    lines.push(`**Target:** ${escapeMarkdown(r.targetType)}`);
    lines.push('');
    lines.push('**Why**');
    lines.push('');
    lines.push(escapeMarkdown(r.rationale));
    lines.push('');
    lines.push('**Evidence**');
    lines.push('');
    lines.push(`- ${r.evidence.length} evidence references`);
    lines.push(`- ${r.targetIds.length} targets`);
    lines.push('');
    lines.push('**Impact**');
    lines.push('');
    lines.push('Potentially affects:');
    lines.push('');
    lines.push(`- ${r.impact.affectedElements} elements`);
    lines.push(`- ${r.impact.affectedComponents} components`);
    lines.push(`- ${r.impact.affectedThemes.length} themes`);
    lines.push('');
    if (r.verification.length > 0) {
      lines.push('**Verification**');
      lines.push('');
      lines.push('Remeasure the affected components and compare regression results.');
      lines.push('');
    }
  }
  return lines.join('\n');
}

// ─── §27 Verification ──────────────────────────────────────────────

export function renderVerification(report: UIQualityReport): string {
  const lines: string[] = [];
  lines.push('## 11. Verification Criteria');
  lines.push('');
  const criteria = report.recommendations.flatMap((r) =>
    r.verification.map((c) => ({ recommendationId: r.id, ...c })),
  );
  if (criteria.length === 0) {
    lines.push('No verification criteria were generated for the selected scope.');
    lines.push('');
    return lines.join('\n');
  }
  lines.push('| ID | Target | Metric | Rule | Expected |');
  lines.push('|---|---|---|---|---|');
  let idx = 1;
  for (const c of criteria) {
    lines.push(
      `| V-${String(idx).padStart(3, '0')} | ${escapeTableCell(c.recommendationId)} | ${escapeTableCell(c.metricId)} | ${escapeTableCell(c.ruleId)} | ${escapeTableCell(c.expectedState)} |`,
    );
    idx++;
  }
  lines.push('');
  return lines.join('\n');
}

// ─── §32 Release Gate ──────────────────────────────────────────────

export function renderReleaseGate(report: UIQualityReport): string {
  const lines: string[] = [];
  lines.push('## 12. Release Gate');
  lines.push('');
  // Release gate is derived from report facts (not re-evaluated).
  const highFindings = report.findings.filter((f) => f.severity === 'HIGH');
  const newFailures = report.regression?.summary.newFailures ?? 0;
  const conformancePass =
    report.conformance !== undefined && report.conformance.failed === 0 && report.conformance.errors === 0;

  let status: 'PASS' | 'WARN' | 'FAIL';
  if (highFindings.length > 0 || newFailures > 0) {
    status = highFindings.length > 2 ? 'FAIL' : 'WARN';
  } else if (report.findings.length === 0) {
    status = 'PASS';
  } else {
    status = 'WARN';
  }

  lines.push(`**Status:** ${status}`);
  lines.push('');
  lines.push('### Reasons');
  lines.push('');
  if (highFindings.length > 0) {
    lines.push(`- ${highFindings.length} HIGH severity findings`);
  }
  if (newFailures > 0) {
    lines.push(`- ${newFailures} NEW_FAILURE`);
  }
  if (conformancePass) {
    lines.push(`- ${report.conformance!.level} conformance completed`);
  }
  if (highFindings.length === 0 && newFailures === 0 && !conformancePass) {
    lines.push('- No blocking issues detected');
  }
  lines.push('');
  return lines.join('\n');
}

// ─── §33 Reproducibility ───────────────────────────────────────────

export function renderReproducibility(report: UIQualityReport): string {
  const lines: string[] = [];
  lines.push('## 13. Reproducibility');
  lines.push('');
  lines.push('| Property | Value |');
  lines.push('|---|---|');
  lines.push(
    `| Engine | ${escapeTableCell(report.reproducibility.engine.name)} ${escapeTableCell(report.reproducibility.engine.version)} |`,
  );
  lines.push(
    `| Snapshot | ${escapeTableCell(report.scope.snapshotIds.length > 0 ? report.scope.snapshotIds.join(', ') : 'N/A')} |`,
  );
  lines.push(
    `| Viewport | ${escapeTableCell(report.scope.viewports.length > 0 ? report.scope.viewports.join(', ') : 'N/A')} |`,
  );
  lines.push(
    `| Theme | ${escapeTableCell(report.scope.themes.length > 0 ? report.scope.themes.join(', ') : 'N/A')} |`,
  );
  lines.push(`| Metric Versions | ${escapeTableCell(joinList(report.reproducibility.metricVersions))} |`);
  lines.push(`| Rule Versions | ${escapeTableCell(joinList(report.reproducibility.ruleVersions))} |`);
  if (report.reproducibility.configuration) {
    lines.push(
      `| Configuration Hash | ${escapeTableCell(JSON.stringify(report.reproducibility.configuration))} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}
